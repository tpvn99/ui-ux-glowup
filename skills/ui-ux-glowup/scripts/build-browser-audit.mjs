#!/usr/bin/env node
// Regenerates audit.browser.js: the whole audit (probe + analysis + report) as one self-contained
// snippet to paste into the DevTools console of any tab — ideal for pages behind a login, or when
// an agent drives the user's own browser (e.g. Claude in Chrome's javascript tool).
//
// Usage: node build-browser-audit.mjs        (run after changing anything in lib/)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { isMain } from "./lib/browser.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const MODULES = ["lib/color.mjs", "lib/analyze.mjs", "lib/probe.mjs", "lib/report.mjs"];

/** Strip ES module syntax so the libs can live in one function scope. */
export function stripModule(source) {
  return source.replace(/^import [^;]+;\n/gm, "").replace(/^export \{[^}]*\};?\n/gm, "").replace(/^export /gm, "");
}

export function buildBrowserAudit() {
  const body = MODULES.map((m) => `// ---- ${m} ----\n` + stripModule(readFileSync(join(here, m), "utf8"))).join("\n");
  return `// ui-ux-glowup — in-browser audit. GENERATED by build-browser-audit.mjs, do not edit.
// Paste into the DevTools console of the page to audit (works on logged-in pages).
// Audits the current viewport only: run it once at desktop width and once with the
// device toolbar at 390px to get the mobile checks.
// Returns { report, result } and prints the report.
(() => {
${body}
const data = collectPageData();
const findings = analyze(data, data);
const result = {
  target: location.href,
  note: "Viewport: " + innerWidth + "px (single-viewport audit — rerun at 390px for mobile checks)",
  ...score(findings),
  findings,
  tokens: summarizeTokens(data),
};
const report = formatReport(result);
console.log(report);
return { report, result };
})();
`;
}

if (isMain(import.meta.url)) {
  const out = join(here, "audit.browser.js");
  writeFileSync(out, buildBrowserAudit());
  console.log(out);
}
